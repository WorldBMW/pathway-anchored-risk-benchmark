#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""_si_append_v28.py — 把 v28 重做实验的 run 级明细累积追加到 SI。

SI 是累积式文档（不能从 md 重建，否则丢表），因此这里用 python-docx 打开
Supplemental_Information_Patterns.docx，追加两张表后原地保存。所有数字直接来自
results/regate_v28.json 与 results/outer_refit_v28.json，不手打。

用法：python scripts/_si_append_v28.py [--dry]
"""
from __future__ import annotations

import argparse
import json
import shutil
from datetime import date
from pathlib import Path

from docx import Document
from docx.shared import Pt

ROOT = Path(__file__).resolve().parent.parent
P = ROOT / "papers" / "20_MRP-ST-Repair_Patterns"
SI = P / "Supplemental_Information_Patterns.docx"
REG = ROOT / "results" / "regate_v28.json"
OUT = ROOT / "results" / "outer_refit_v28.json"


def f(v, nd=4):
    if v is None:
        return "n/a"
    try:
        if v != v:
            return "n/a"
    except Exception:
        pass
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def add_table(doc, caption, header, rows):
    doc.add_paragraph()
    p = doc.add_paragraph()
    r = p.add_run(caption)
    r.bold = True
    r.font.size = Pt(9)
    t = doc.add_table(rows=1, cols=len(header))
    try:
        t.style = "Table Grid"
    except KeyError:
        pass
    for i, h in enumerate(header):
        c = t.rows[0].cells[i]
        c.text = h
        for par in c.paragraphs:
            for run in par.runs:
                run.bold = True
                run.font.size = Pt(8)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = v
            for par in cells[i].paragraphs:
                for run in par.runs:
                    run.font.size = Pt(8)
    return t


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry", action="store_true")
    args = ap.parse_args()
    reg = json.loads(REG.read_text(encoding="utf-8"))
    runs = reg["runs"]

    # ---------------- Table S18: 零分布、门限与身份解码（run 级）
    cap18 = (
        "Table S18. Archived unit-level null versus group-preserving null, and the "
        "three-object acceptance readout, run by run. "
        "Both nulls use B = 2,000 refit permutations, permutation seed 20261010 and "
        "the same leave-one-unit-out ridge probe (alpha = 1, within-fold "
        "standardisation, no intercept). sigma_group is the scale of the "
        "within-group permutation; where the label does not vary within group it is "
        "zero and the group-conditional LDI is undefined, reported as n/a. "
        "p_free and p_group are permutation p values from the same batches. "
        "id_knn_lift is the leave-one-out nearest-neighbour same-group hit rate "
        "divided by the same-group prior; id_pair_auc is the AUROC separating "
        "same-group from different-group embedding distances. Delta = tau_LOO - "
        "tau_LGO. Cervical rows use the frozen slice-level embeddings and donor "
        "keys (35 sections, 34 donors). "
        "Source: results/regate_v28.json, generated by scripts/exp_regate_v28.py."
    )
    h18 = ["cohort (arm)", "seed", "lambda", "tau_LOO", "tau_LGO", "Delta",
           "sigma_free", "sigma_group", "LDI_free", "LDI_group", "p_free",
           "p_group", "id_knn_lift", "id_pair_auc"]
    rows18 = []
    for r in runs:
        rows18.append([
            f"{r['domain']}" + (f" ({r['arm']})" if r.get("arm") else ""),
            str(r["seed"]), f(r["lam"], 1), f(r["tau_loo"]), f(r["tau_lgo"]),
            f(r["inflation"]), f(r["sigma_free"]), f(r["sigma_group"]),
            f(r["ldi_free"], 2), f(r["ldi_group"], 2), f(r["p_free"], 4),
            f(r["p_group"], 4), f(r.get("id_knn_lift"), 2),
            f(r.get("id_pair_auc"), 3),
        ])

    # ---------------- Table S19: 名义指标、重编码敏感性与外层重拟合
    cap19 = (
        "Table S19. Nominal multiclass readouts, class-code recoding sensitivity, "
        "and the outer-loop refit. Panels A-C use per-class one-versus-rest "
        "group-holdout probes, which do not use the class codes as quantities. "
        "Recoding sensitivity recomputes tau_LOO across R = 20 random relabellings "
        "of the class codes (seed 20261011); the same relabelling is applied to the "
        "nominal metric as a control and changes it by at most 2e-16. "
        "Panel D refits encoder, adversary and probe inside every outer fold on HAR, "
        "so the held-out subject contributes nothing to representation learning; it "
        "is one cohort, one training seed and two doses, because each fold retrains "
        "a representation. "
        "Sources: results/regate_v28.json and results/outer_refit_v28.json."
    )
    h19 = ["cohort (arm)", "seed", "lambda", "classes", "macro OVR AUROC",
           "balanced accuracy", "tau_LOO recoding SD", "tau_LOO recoding range",
           "AUROC change under recoding"]
    rows19 = []
    for r in runs:
        if "macro_ovr_auc" not in r:
            continue
        rows19.append([
            f"{r['domain']}" + (f" ({r['arm']})" if r.get("arm") else ""),
            str(r["seed"]), f(r["lam"], 1), str(r.get("n_classes", "-")),
            f(r.get("macro_ovr_auc"), 3), f(r.get("balanced_acc"), 3),
            f(r.get("tau_loo_recode_sd")), f(r.get("tau_loo_recode_range")),
            f(r.get("auc_recode_delta")),
        ])
    outer = []
    if OUT.exists():
        od = json.loads(OUT.read_text(encoding="utf-8"))
        for r in od["runs"]:
            outer.append([
                f"{r['domain']} (outer refit)", str(r["seed"]), f(r["lam"], 1),
                f"{r['G']} folds", f"tau_LGO frozen {r['tau_lgo_frozen']:.4f}",
                f"tau_LGO outer {r['tau_outer_lgo']:.4f}",
                f"fold SD {r['fold_sd']:.4f}",
                f"frozen - outer {r['optimism']:+.4f}",
                f"tau_LOO {r['tau_loo_all']:.4f}",
            ])

    if args.dry:
        print(f"Table S18: {len(rows18)} rows")
        print(f"Table S19: {len(rows19)} rows (+{len(outer)} outer-refit rows)")
        return

    bak = SI.with_name(f"Supplemental_Information_Patterns_v28pre_{date.today():%Y%m%d}.docx")
    if not bak.exists():
        shutil.copy2(SI, bak)
    doc = Document(SI)
    add_table(doc, cap18, h18, rows18)
    if outer:
        add_table(doc, cap19 + " Panel D is appended at the end of Table S19.",
                  h19, rows19)
        doc.add_paragraph()
        p = doc.add_paragraph()
        run = p.add_run("Table S19, panel D. Outer-loop refit (encoder, adversary "
                        "and probe refitted inside each outer fold).")
        run.bold = True
        run.font.size = Pt(9)
        add_table(doc, "", ["cohort", "seed", "lambda", "folds",
                            "tau_LGO frozen", "tau_LGO outer", "fold SD",
                            "frozen minus outer", "tau_LOO (all units)"], outer)
    else:
        add_table(doc, cap19, h19, rows19)
    doc.save(SI)
    print(f"appended to {SI.name}: S18 ({len(rows18)} rows), "
          f"S19 ({len(rows19)}+{len(outer)} rows); backup {bak.name}")


if __name__ == "__main__":
    main()
